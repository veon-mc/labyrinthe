package g64889.dev3.labyrinthe.model.enumeration;

/**
 * Represents the four cardinal directions used in the game.
 * <p>
 * Directions are used for tile openings, board insertions,
 * and player movement orientation.
 */
public enum Direction {

    /** North direction (up). */
    NORTH,

    /** East direction (right). */
    EAST,

    /** South direction (down). */
    SOUTH,

    /** West direction (left). */
    WEST
}