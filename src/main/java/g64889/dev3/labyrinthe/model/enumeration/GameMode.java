package g64889.dev3.labyrinthe.model.enumeration;

/**
 * Represents the different game modes available.
 * <p>
 * The game mode influences how the game behaves and which rules are applied.
 */
public enum GameMode {

    /**
     * Standard game mode with all default rules enabled.
     */
    STANDARD,

    /**
     * Simplified game mode with reduced or adapted rules.
     */
    SIMPLIFIED
}